test('text conditions match the old case-insensitive all/any flow and survive reopening', async ({ page }) => {
  await page.goto('/')
  const grid = page.getByRole('grid', { name: 'Quick-start products' })
  await grid.getByRole('button', { name: 'Filter Name', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Filter Name', exact: true })
  await dialog.getByRole('textbox', { name: 'Name filter', exact: true }).fill('AMBER')
  await dialog.getByRole('button', { name: 'Add condition', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Condition 2', exact: true }).selectOption('equals')
  await dialog.getByRole('textbox', { name: 'Name filter 2', exact: true }).fill('blue card')
  await dialog.getByRole('combobox', { name: 'Match', exact: true }).selectOption('any')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(grid.getByRole('gridcell', { name: 'Amber poster', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: 'Blue card', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: 'Cedar label', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  await page.reload()
  await expect(grid.getByRole('gridcell')).toHaveCount(8)
  await grid.getByRole('button', { name: 'Filter Name', exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: 'Match', exact: true })).toHaveValue('any')
  await expect(dialog.getByRole('textbox', { name: 'Name filter', exact: true })).toHaveValue('AMBER')
  await expect(dialog.getByRole('textbox', { name: 'Name filter 2', exact: true })).toHaveValue('blue card')
  await dialog.getByRole('combobox', { name: 'Match', exact: true }).selectOption('all')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(grid.getByRole('gridcell')).toHaveCount(0)
  await grid.getByRole('button', { name: 'Filter Name', exact: true }).click()
  await dialog.getByRole('button', { name: 'Clear filter', exact: true }).click()
  await expect(grid.getByRole('gridcell')).toHaveCount(12)
})

test('numeric validation preserves the prior query, and clearing one column keeps the others', async ({ page }) => {
  await page.goto('/')
  const grid = page.getByRole('grid', { name: 'Quick-start products' })
  await grid.getByRole('button', { name: 'Filter Quantity', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Filter Quantity', exact: true })
  await dialog.getByRole('combobox', { name: 'Condition 1', exact: true }).selectOption('greater-than-or-equal')
  await dialog.getByRole('textbox', { name: 'Quantity filter', exact: true }).fill('24')
  await dialog.getByRole('button', { name: 'Add condition', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Condition 2', exact: true }).selectOption('less-than')
  await dialog.getByRole('textbox', { name: 'Quantity filter 2', exact: true }).fill('invalid')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('Enter a valid number.')
  await expect(grid.getByRole('gridcell')).toHaveCount(12)
  await dialog.getByRole('textbox', { name: 'Quantity filter 2', exact: true }).fill('40')
  await dialog.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(grid.getByRole('gridcell')).toHaveCount(8)
  await grid.getByRole('button', { name: 'Filter Active', exact: true }).click()
  await page.getByRole('combobox', { name: 'Active filter', exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Apply filter', exact: true }).click()
  await expect(grid.getByRole('gridcell')).toHaveCount(4)
  await expect(grid.getByRole('gridcell', { name: 'Blue card', exact: true })).toBeVisible()
  await grid.getByRole('button', { name: 'Filter Active', exact: true }).click()
  await page.getByRole('button', { name: 'Clear filter', exact: true }).click()
  await expect(grid.getByRole('gridcell')).toHaveCount(8)
  await grid.getByRole('button', { name: 'Filter Quantity', exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: 'Condition 1', exact: true })).toHaveValue('greater-than-or-equal')
  await dialog.getByRole('button', { name: 'Clear filter', exact: true }).click()
  await expect(grid.getByRole('gridcell')).toHaveCount(12)
})

