test('dragging headers selects full rows and columns, and resizing leaves editing anchored', async ({ page }) => {
  await page.goto('/')
  const grid = page.getByRole('grid', { name: 'Quick-start products' })
  async function drag(from: import('@playwright/test').Locator, to: import('@playwright/test').Locator) {
    const start = (await from.boundingBox())!, end = (await to.boundingBox())!
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
    await page.mouse.down()
    await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 6 })
    await page.mouse.up()
  }
  await drag(grid.getByRole('button', { name: 'Select column Name', exact: true }), grid.getByRole('button', { name: 'Select column Quantity', exact: true }))
  await expect(grid.getByRole('gridcell', { selected: true })).toHaveCount(6)
  await drag(grid.getByRole('button', { name: 'Select row 1', exact: true }), grid.getByRole('button', { name: 'Select row 3', exact: true }))
  await expect(grid.getByRole('gridcell', { selected: true })).toHaveCount(12)
  const resize = grid.getByRole('separator', { name: 'Resize Name', exact: true })
  const before = (await grid.getByRole('columnheader', { name: 'Name', exact: true }).boundingBox())!
  const handle = (await resize.boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down(); await page.mouse.move(handle.x + handle.width / 2 + 80, handle.y + handle.height / 2); await page.mouse.up()
  await expect(resize).toHaveAttribute('aria-valuenow', '240')
  expect((await grid.getByRole('columnheader', { name: 'Name', exact: true }).boundingBox())!.width).toBeCloseTo(before.width + 80, 0)
  await grid.getByRole('gridcell', { name: '24', exact: true }).press('Shift+Tab')
  await expect(grid.getByRole('gridcell', { name: 'Blue card', exact: true })).toBeFocused()
  await expect(grid.getByRole('gridcell', { selected: true })).toHaveText(['Blue card'])
  const handleAfter = (await resize.boundingBox())!
  await page.mouse.move(handleAfter.x + handleAfter.width / 2, handleAfter.y + handleAfter.height / 2)
  await page.mouse.down()
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await page.mouse.move(handleAfter.x + 100, handleAfter.y + handleAfter.height / 2)
  await page.mouse.up()
  await expect(resize).toHaveAttribute('aria-valuenow', '240')
  await grid.getByRole('gridcell', { name: 'Amber poster', exact: true }).dblclick()
  await expect(page.getByRole('button', { name: 'Apply value', exact: true })).toBeEnabled()
  const cell = (await grid.getByRole('gridcell', { name: 'Amber poster', exact: true }).boundingBox())!
  const editor = (await page.getByRole('textbox', { name: 'Name', exact: true }).boundingBox())!
  expect(Math.abs(editor.width - cell.width)).toBeLessThan(3)
  expect(Math.abs(editor.y - cell.y)).toBeLessThan(3)
})

test('pasting expands from the active cell and commits the complete matrix; invalid input remains recoverable', async ({ page }) => {
  await page.goto('/')
  const grid = page.getByRole('grid', { name: 'Quick-start products' })
  const origin = grid.getByRole('gridcell', { name: 'Amber poster', exact: true })
  await origin.click()
  await page.evaluate(() => { const source = document.createElement('textarea'); source.setAttribute('aria-label', 'Clipboard source'); document.body.append(source) })
  const clipboard = page.getByRole('textbox', { name: 'Clipboard source', exact: true })
  await clipboard.fill('Pasted one\t41\nPasted two\t42')
  await clipboard.press('Control+a'); await clipboard.press('Control+c')
  await origin.focus(); await origin.press('Control+v')
  await clipboard.evaluate(element => element.remove())
  await expect(grid.getByRole('gridcell', { name: 'Pasted one', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: '41', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: 'Pasted two', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: '42', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: 'Cedar label', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  await page.reload()
  const pasted = grid.getByRole('gridcell', { name: 'Pasted one', exact: true })
  await expect(pasted).toBeVisible()
  await pasted.evaluate(element => {
    const event = new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData: new DataTransfer() })
    event.clipboardData!.setData('text/plain', 'Must not partially apply\tinvalid')
    element.dispatchEvent(event)
    if (!event.defaultPrevented) throw new Error('The paste event was not handled.')
  })
  await expect(page.getByRole('alert')).toContainText('Enter a non-negative whole number.')
  await expect(pasted).toBeVisible()
  await expect(page.getByRole('textbox')).toHaveValue('Must not partially apply\tinvalid')
  await page.reload()
  await page.getByRole('button', { name: 'Resume editing', exact: true }).click()
  await expect(page.getByRole('textbox')).toHaveValue('Must not partially apply\tinvalid')
  await expect(pasted).toBeVisible()
})

test('changing cells commits valid scalar input and keeps invalid input at its original target', async ({ page }) => {
  await page.goto('/')
  const grid = page.getByRole('grid', { name: 'Quick-start products' })
  const quantity = grid.getByRole('gridcell', { name: '12', exact: true })
  const next = grid.getByRole('gridcell', { name: 'Blue card', exact: true })
  await quantity.dblclick()
  const input = page.getByRole('textbox', { name: 'Quantity', exact: true })
  await input.fill('invalid')
  await next.click()
  await expect(input).toHaveValue('invalid')
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await expect(input).toBeFocused()
  await expect(quantity).toHaveAttribute('aria-selected', 'true')
  await expect(next).toHaveAttribute('aria-selected', 'false')
  for (const name of ['Select column Name', 'Select row 2', 'Select all cells']) {
    await grid.getByRole('button', { name, exact: true }).click()
    await expect(input).toBeFocused()
    await expect(grid.getByRole('gridcell', { selected: true })).toHaveCount(1)
    await expect(quantity).toHaveAttribute('aria-selected', 'true')
  }
  await input.fill('43')
  await next.click()
  await expect(input).toHaveCount(0)
  await expect(grid.getByRole('gridcell', { name: '43', exact: true })).toBeVisible()
  await expect(next).toBeFocused()
  await expect(next).toHaveAttribute('aria-selected', 'true')
  await next.press('F2')
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Next product')
  await grid.getByRole('gridcell', { name: 'Cedar label', exact: true }).click()
  await expect(grid.getByRole('gridcell', { name: 'Next product', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  await page.reload()
  await expect(grid.getByRole('gridcell', { name: '43', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: 'Next product', exact: true })).toBeVisible()
})
