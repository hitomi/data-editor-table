test('in-cell keyboard editing validates, commits with Tab, cancels with Escape, and retains rapid typing', async ({ page }) => {
  await page.goto('/')
  const grid = page.getByRole('grid', { name: 'Quick-start products' })
  const quantity = grid.getByRole('gridcell', { name: '12', exact: true })
  await quantity.dblclick()
  const input = page.getByRole('textbox', { name: 'Quantity', exact: true })
  await expect(input).toBeFocused()
  await expect(page.getByRole('button', { name: 'Apply value', exact: true })).toBeEnabled()
  const cellBox = await quantity.boundingBox(), editorBox = await input.boundingBox()
  expect(Math.abs(cellBox!.x - editorBox!.x)).toBeLessThan(3)
  expect(Math.abs(cellBox!.y - editorBox!.y)).toBeLessThan(3)
  await input.fill('invalid')
  await input.press('Enter')
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await expect(input).toHaveValue('invalid')
  await input.fill('45')
  await input.press('Tab')
  await expect(input).toHaveCount(0)
  await expect(grid.getByRole('gridcell', { name: '45', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: 'Ready', exact: true }).first()).toBeFocused()
  const name = grid.getByRole('gridcell', { name: 'Amber poster', exact: true })
  await name.click()
  await page.keyboard.type('Rapid replacement')
  await page.keyboard.press('Enter')
  await expect(grid.getByRole('gridcell', { name: 'Rapid replacement', exact: true })).toBeVisible()
  await grid.getByRole('gridcell', { name: 'Rapid replacement', exact: true }).press('F2')
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Cancelled')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('textbox', { name: 'Name', exact: true })).toHaveCount(0)
  await expect(grid.getByRole('gridcell', { name: 'Rapid replacement', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  await page.reload()
  await expect(grid.getByRole('gridcell', { name: 'Rapid replacement', exact: true })).toBeVisible()
  await expect(grid.getByRole('gridcell', { name: '45', exact: true })).toBeVisible()
})

