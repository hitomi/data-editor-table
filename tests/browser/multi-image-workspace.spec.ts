import { readFile } from 'node:fs/promises'
import { expect, test } from './test.js'
const files = ['one', 'two', 'three', 'four'].map(name => ({ name: `${name}.svg`, mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"><rect width="2" height="2" fill="blue"/></svg>') }))

test('image imports retain previews across reload, atomically append overflow, retry save and undo saved import', async ({ page }) => {
  await page.goto('/#/multi-image-import')
  const grid = page.getByRole('grid', { name: 'Image import rows' })
  await expect(grid.getByRole('row')).toHaveCount(4)
  await page.getByLabel('Choose images to import').setInputFiles(files)
  await expect(page.getByRole('region', { name: 'Review image import' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Confirm these replacements and new rows' }).press('Escape')
  await expect(page.getByRole('button', { name: 'Cancel task', exact: true })).toBeVisible()
  await expect(grid.getByRole('img')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Review image import' }).getByRole('img')).toHaveCount(4)
  await page.getByRole('checkbox', { name: 'Confirm these replacements and new rows' }).check()
  await page.getByRole('button', { name: 'Apply image import', exact: true }).click()
  await expect(grid.getByRole('row')).toHaveCount(5)
  await expect(grid.getByRole('img')).toHaveCount(4)
  await page.getByRole('button', { name: 'Fail next save', exact: true }).click()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Changes were not saved.')
  await expect(page.getByRole('button', { name: 'Refresh rows', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Refresh rows', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  await page.reload()
  await expect(grid.getByRole('img')).toHaveCount(4)
  await expect(grid.getByRole('img', { name: 'four', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(grid.getByRole('row')).toHaveCount(4)
  await expect(grid.getByRole('img')).toHaveCount(0)
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Refresh rows', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  await page.reload()
  await expect(grid.getByRole('row')).toHaveCount(4)
  await expect(grid.getByRole('img')).toHaveCount(0)
})

